/**
 * TFast Tool Gateway → TikTok MCP.
 *
 *   TFast Agent → TFast Tool Gateway → TikTok MCP → TikTok Ads
 *
 * Responsibilities (all enforced HERE, never by the agent):
 *   1. Resolve tenant: agency_id/client_id → connection → advertiser_id.
 *      Agents can NEVER supply an advertiser_id arbitrarily — the gateway
 *      injects it from the connection registry.
 *   2. Enforce permissions from the connection registry.
 *   3. Wrap every write op in: dry-run → approval → budget governor → audit.
 *   4. Idempotency keys for all mutations.
 *
 * Transport: official TikTok for Business MCP Server via Streamable HTTP.
 * Config-driven: TIKTOK_MCP_URL + TIKTOK_MCP_TOKEN from .env.
 * Tool names are discovered from the MCP server (keyword-scored mapping),
 * so this gateway works regardless of the server's exact tool naming.
 */
import { randomUUID } from 'node:crypto';
import { z } from 'zod';
import type { TenantScope } from '../core/tenant.js';
import { assertClientScoped, assertSameTenant } from '../core/tenant.js';
import { McpClient } from './mcp-client.js';
import { config } from '../config.js';
import { pool } from '../db/pool.js';
import { runSafetyPipeline, type MutationOutcome } from './safety-pipeline.js';
import { getAccessToken } from '../providers/tiktok-oauth.js';

export type { MutationOutcome };

export const TikTokOperations = [
  'report.advertiser', 'report.campaign', 'report.ad_group', 'report.ad',
  'campaign.get', 'campaign.update', 'campaign.create',
  'adgroup.get', 'adgroup.update', 'adgroup.create',
  'ad.get', 'ad.update', 'ad.create',
  'creative.get', 'audience.get', 'audience.create',
  'account.pause_all', // emergency stop helper
] as const;
export type TikTokOperation = (typeof TikTokOperations)[number];

const READ_OPS: readonly TikTokOperation[] = [
  'report.advertiser', 'report.campaign', 'report.ad_group', 'report.ad',
  'campaign.get', 'adgroup.get', 'ad.get', 'creative.get', 'audience.get',
];

export interface ResolvedTikTokContext {
  connection_id: string;
  advertiser_id: string;
  platform: 'tiktok';
  scope: TenantScope & { client_id: string; ad_account_id: string };
}

export interface GatewayRequest {
  scope: TenantScope;
  operation: TikTokOperation;
  params: Record<string, unknown>;
  /** required for writes; generated by gateway */
  idempotencyKey?: string;
}

export interface TikTokHealth {
  ok: boolean;
  connection_id?: string;
  advertiser_id?: string;
  tools?: number;
  message: string;
}

export const GatewayResponseSchema = z.object({
  ok: z.boolean(),
  mode: z.enum(['dry_run', 'execute']),
  data: z.unknown().optional(),
  dry_run: z.unknown().optional(), // DryRunResult when mode=dry_run
  error: z.string().optional(),
});

export type GatewayResponse = z.infer<typeof GatewayResponseSchema>;

export interface ConnectionLookup {
  resolveForClient(scope: TenantScope, platform: 'tiktok'): Promise<ResolvedTikTokContext>;
  permissionsFor(connectionId: string): Promise<string[]>;
}

// ── MCP transport ─────────────────────────────────────────

const clientsByToken = new Map<string, McpClient>();
const toolCacheByToken = new Map<string, Map<string, string>>(); // token → (operation → tool name)

/** Client for a token string (per-connection OAuth token, or the env fallback). */
function client(token?: string): McpClient {
  if (!config.TIKTOK_MCP_URL) {
    throw new Error('TIKTOK_MCP_NOT_CONFIGURED: set TIKTOK_MCP_URL (and TIKTOK_MCP_TOKEN) in .env');
  }
  const key = token ?? config.TIKTOK_MCP_TOKEN ?? '';
  if (!clientsByToken.has(key)) {
    clientsByToken.set(key, new McpClient(config.TIKTOK_MCP_URL, key || undefined));
  }
  return clientsByToken.get(key)!;
}

/** Resolve the connection's OAuth access token (auto-refresh), else env token. */
async function resolveConnectionToken(ctx: ResolvedTikTokContext): Promise<string | undefined> {
  const { rows } = await pool.query<{ credential_reference: string }>(
    `SELECT credential_reference FROM connections WHERE id = $1`,
    [ctx.connection_id],
  );
  const reference = rows[0]?.credential_reference;
  if (reference?.startsWith('tiktok:oauth:') || reference?.startsWith('tiktok-mcp:oauth:')) {
    return getAccessToken(ctx.scope, reference);
  }
  return undefined; // fall back to TIKTOK_MCP_TOKEN
}

/** TikTok caps tool calls at 3 QPS per user — keep a safe 350ms gap per token. */
const lastCallByToken = new Map<string, number>();
async function throttle(tokenKey: string): Promise<void> {
  const last = lastCallByToken.get(tokenKey) ?? 0;
  const wait = last + 350 - Date.now();
  if (wait > 0) await new Promise((r) => setTimeout(r, wait));
  lastCallByToken.set(tokenKey, Date.now());
}

/** Keyword groups used to match operations → real MCP tool names. */
const TOOL_KEYWORDS: Record<TikTokOperation, string[][]> = {
  'report.advertiser': [['report', 'advertiser'], ['insight', 'advertiser'], ['report', 'integrated']],
  'report.campaign': [['report', 'campaign'], ['insight', 'campaign'], ['report', 'integrated']],
  'report.ad_group': [['report', 'adgroup'], ['report', 'ad_group'], ['insight', 'adgroup'], ['report', 'integrated']],
  'report.ad': [['report', 'ad'], ['insight', 'ad'], ['report', 'integrated']],
  'campaign.get': [['campaign', 'get'], ['campaign', 'list'], ['campaign', 'detail']],
  'campaign.update': [['campaign', 'update'], ['campaign', 'edit']],
  'campaign.create': [['campaign', 'create']],
  'adgroup.get': [['adgroup', 'get'], ['adgroup', 'list'], ['ad_group', 'get']],
  'adgroup.update': [['adgroup', 'update'], ['adgroup', 'edit']],
  'adgroup.create': [['adgroup', 'create']],
  'ad.get': [['ad', 'get'], ['ad', 'list']],
  'ad.update': [['ad', 'update'], ['ad', 'edit']],
  'ad.create': [['ad', 'create']],
  'creative.get': [['creative', 'get'], ['creative', 'list']],
  'audience.get': [['audience', 'get'], ['audience', 'list']],
  'audience.create': [['audience', 'create']],
  'account.pause_all': [['campaign', 'pause'], ['account', 'pause'], ['pause', 'all']],
};

async function resolveToolName(operation: TikTokOperation, token?: string): Promise<string> {
  const cacheKey = token ?? '';
  let toolCache = toolCacheByToken.get(cacheKey);
  if (!toolCache) {
    const tools = await client(token).listTools();
    toolCache = new Map();
    for (const op of TikTokOperations) {
      let best = '';
      let bestScore = 0;
      for (const tool of tools) {
        const normalized = tool.toLowerCase().replace(/[^a-z0-9]/g, '');
        let score = 0;
        for (const group of TOOL_KEYWORDS[op]) {
          const joined = group.join('');
          if (normalized.includes(joined)) score += joined.length;
        }
        if (score > bestScore) {
          bestScore = score;
          best = tool;
        }
      }
      if (best) toolCache.set(op, best);
    }
    toolCacheByToken.set(cacheKey, toolCache);
  }
  const tool = toolCache.get(operation);
  if (!tool) {
    throw new Error(
      `TIKTOK_MCP_TOOL_NOT_FOUND: no tool matched "${operation}". ` +
      `Available tools: ${[...(await client(token).listTools())].join(', ')}`,
    );
  }
  return tool;
}

/** Raw call with advertiser_id auto-injected from the connection registry. */
async function callTikTokMCP(
  ctx: ResolvedTikTokContext,
  operation: TikTokOperation,
  params: Record<string, unknown>,
): Promise<unknown> {
  const token = await resolveConnectionToken(ctx);
  await throttle(token ?? ctx.connection_id);
  const tool = await resolveToolName(operation, token);
  const args = params.advertiser_id
    ? params
    : ctx.advertiser_id
      ? { advertiser_id: ctx.advertiser_id, ...params }
      : params;
  const result = await client(token).callTool(tool, args);
  return result.parsed;
}

/** Lightweight end-to-end check: registry -> OAuth token -> MCP handshake -> tools/list. */
export async function probeTikTokMCP(
  lookup: ConnectionLookup,
  scope: TenantScope,
): Promise<TikTokHealth> {
  try {
    assertClientScoped(scope);
    const ctx = await lookup.resolveForClient(scope, 'tiktok');
    assertSameTenant(scope, ctx.scope);
    const token = await resolveConnectionToken(ctx);
    const tools = await client(token).listTools();
    return {
      ok: true,
      connection_id: ctx.connection_id,
      advertiser_id: ctx.advertiser_id,
      tools: tools.length,
      message: `Connected. TikTok MCP exposed ${tools.length} tools.`,
    };
  } catch (error) {
    return {
      ok: false,
      message: error instanceof Error ? error.message : String(error),
    };
  }
}

// ── Read path ─────────────────────────────────────────────

export async function tiktokGateway(lookup: ConnectionLookup, req: GatewayRequest): Promise<GatewayResponse> {
  assertClientScoped(req.scope);
  const ctx = await lookup.resolveForClient(req.scope, 'tiktok');
  assertSameTenant(req.scope, ctx.scope);

  const isWrite = !READ_OPS.includes(req.operation);
  const perms = await lookup.permissionsFor(ctx.connection_id);
  const needs = isWrite ? ['tiktok:write'] : ['tiktok:read'];
  for (const p of needs) {
    if (!perms.includes(p)) {
      return { ok: false, mode: isWrite ? 'dry_run' : 'execute', error: `PERMISSION_DENIED: missing ${p}` };
    }
  }

  if (!isWrite) {
    try {
      return { ok: true, mode: 'execute', data: await callTikTokMCP(ctx, req.operation, req.params) };
    } catch (err) {
      return { ok: false, mode: 'execute', error: err instanceof Error ? err.message : String(err) };
    }
  }

  // Writes go through the full safety pipeline.
  const outcome = await executeTikTokMutation(lookup, req);
  if (!outcome.ok) {
    return { ok: false, mode: 'dry_run', dry_run: outcome.dry_run, error: outcome.error };
  }
  return {
    ok: true,
    mode: outcome.executed ? 'execute' : 'dry_run',
    data: outcome.executed ? outcome.execution_result : undefined,
    dry_run: outcome.dry_run,
  };
}

// ── Mutation pipeline: dry-run → approval → budget governor → audit ──
// All policy decisions live in the shared safety pipeline.
// This adapter only provides TikTok context resolution + the executor.

/** Conservative action-type inference for policy lookup. */
function inferActionType(operation: TikTokOperation, params: Record<string, unknown>): string {
  if (operation === 'account.pause_all') return 'change_budget_over_25_percent'; // owner approval by default
  if (operation === 'ad.update') return 'pause_underperforming_ad';
  if (operation === 'campaign.create' || operation === 'adgroup.create') return 'launch_campaign';
  if (operation === 'ad.create' || operation === 'audience.create') return 'create_new_ad';
  if (operation === 'campaign.update' || operation === 'adgroup.update') {
    const hasBudget = 'budget' in params || 'daily_budget' in params || 'budget_mode' in params;
    return hasBudget ? 'change_budget_over_25_percent' : 'create_new_ad';
  }
  return 'change_budget_over_25_percent'; // most restrictive default
}

export async function executeTikTokMutation(
  lookup: ConnectionLookup,
  req: GatewayRequest,
): Promise<MutationOutcome> {
  assertClientScoped(req.scope);
  const ctx = await lookup.resolveForClient(req.scope, 'tiktok');
  assertSameTenant(req.scope, ctx.scope);
  const perms = await lookup.permissionsFor(ctx.connection_id);

  const budget = extractBudgetParams(req.params);
  return runSafetyPipeline({
    scope: ctx.scope,
    platform: 'tiktok',
    connection_id: ctx.connection_id,
    account_external_id: ctx.advertiser_id,
    permissions: perms,
    operation: req.operation,
    actionType: inferActionType(req.operation, req.params),
    params: req.params,
    beforeState: await readCurrentState(req.operation, req.params, ctx),
    budget: budget ? { ...budget, currency: budget.currency ?? 'USD' } : null,
    executor: () => callTikTokMCP(ctx, req.operation, req.params),
    idempotencyKey: req.idempotencyKey,
  });
}

/** Extract budget-change fields from mutation params (tolerant). */
function extractBudgetParams(params: Record<string, unknown>): {
  current?: number; proposed?: number; currency?: string; deltaPerDay?: number; description: string;
} | null {
  const budget = (params.budget ?? params.daily_budget) as
    | number
    | string
    | { amount?: number | string; daily_budget?: number | string }
    | undefined;
  if (budget == null) return null;
  const toNum = (v: unknown): number | undefined => {
    const n = typeof v === 'string' ? parseFloat(v) : typeof v === 'number' ? v : NaN;
    return Number.isFinite(n) ? n : undefined;
  };
  if (typeof budget === 'object') {
    const proposed = toNum(budget.amount ?? budget.daily_budget);
    return proposed != null
      ? { proposed, currency: (params.currency as string) ?? 'USD', description: `Budget change to ${proposed}` }
      : null;
  }
  const proposed = toNum(budget);
  return proposed != null
    ? { proposed, currency: (params.currency as string) ?? 'USD', description: `Budget change to ${proposed}` }
    : null;
}

/** Best-effort current-state read for the dry-run diff. Never throws. */
async function readCurrentState(
  operation: TikTokOperation,
  params: Record<string, unknown>,
  ctx: ResolvedTikTokContext,
): Promise<Record<string, unknown>> {
  const idKey = { campaign: 'campaign_id', adgroup: 'adgroup_id', ad: 'ad_id' }[
    operation.split('.')[0] as 'campaign' | 'adgroup' | 'ad'
  ];
  const getOp = ({ campaign: 'campaign.get', adgroup: 'adgroup.get', ad: 'ad.get' } as const)[
    operation.split('.')[0] as 'campaign' | 'adgroup' | 'ad'
  ];
  if (!idKey || !getOp || params[idKey] == null) return {};
  try {
    const res = (await callTikTokMCP(ctx, getOp, { [idKey]: params[idKey] })) as unknown;
    return (res as Record<string, unknown>) ?? {};
  } catch {
    return {};
  }
}

export function newIdempotencyKey(): string {
  return randomUUID();
}

// ── Human approval → execution path ─────────────────────────

export interface ApprovalRow {
  id: string;
  client_id: string;
  tool_call_id: string;
  action_type: string;
  status: 'pending' | 'approved' | 'rejected' | 'expired';
  required_role: string;
}

/**
 * Executes a pending, human-approved action. The approver's role is
 * checked against required_role; the operation and parameters come from
 * the stored tool_call (agents cannot smuggle new params through approval).
 */
export async function approveAndExecuteMutation(
  lookup: ConnectionLookup,
  approvalId: string,
  scope: TenantScope,
  decidedBy: { user_id: string; role: string },
): Promise<MutationOutcome> {
  assertClientScoped(scope);
  const { rows } = await pool.query<ApprovalRow>(
    `SELECT id, client_id, tool_call_id, action_type, status, required_role
     FROM approvals WHERE id = $1 AND agency_id = $2 AND client_id = $3`,
    [approvalId, scope.agency_id, scope.client_id],
  );
  const approval = rows[0];
  if (!approval) return { ok: false, executed: false, tool_call_id: '', error: 'APPROVAL_NOT_FOUND', message: 'Approval not found.' };
  if (approval.status !== 'pending') {
    return { ok: false, executed: false, tool_call_id: approval.tool_call_id, error: `APPROVAL_${approval.status.toUpperCase()}`, message: `Approval already ${approval.status}.` };
  }
  const { roleAtLeast } = await import('../http/auth.js');
  if (!roleAtLeast(decidedBy.role as never, approval.required_role as never)) {
    return { ok: false, executed: false, tool_call_id: approval.tool_call_id, error: 'FORBIDDEN', message: `Requires ${approval.required_role} role.` };
  }

  const { rows: tcRows } = await pool.query<{ tool: string; proposed_parameters: Record<string, unknown> }>(
    `SELECT tool, proposed_parameters FROM tool_calls WHERE id = $1`,
    [approval.tool_call_id],
  );
  const tc = tcRows[0];
  const operation = tc?.tool?.replace(/^tiktok:/, '') as TikTokOperation;
  if (!tc || !TikTokOperations.includes(operation)) {
    return { ok: false, executed: false, tool_call_id: approval.tool_call_id, error: 'TOOL_CALL_INVALID', message: 'Stored tool call is invalid.' };
  }

  await pool.query(
    `UPDATE approvals SET status = 'approved', decided_by = $2, decided_at = now() WHERE id = $1`,
    [approvalId, decidedBy.user_id],
  );

  // Execute with fresh idempotency key (a new attempt after human review).
  const outcome = await executeTikTokMutation(lookup, {
    scope,
    operation,
    params: tc.proposed_parameters,
    idempotencyKey: newIdempotencyKey(),
  });

  await pool.query(
    `UPDATE tool_calls SET approval_status = 'approved' WHERE id = $1`,
    [approval.tool_call_id],
  );
  return outcome;
}

/** List pending approvals for a client (tenant-scoped). */
export async function listPendingApprovals(scope: TenantScope): Promise<ApprovalRow[]> {
  assertClientScoped(scope);
  const { rows } = await pool.query<ApprovalRow>(
    `SELECT id, client_id, tool_call_id, action_type, status, required_role
     FROM approvals
     WHERE agency_id = $1 AND client_id = $2 AND status = 'pending'
     ORDER BY created_at DESC`,
    [scope.agency_id, scope.client_id],
  );
  return rows;
}
